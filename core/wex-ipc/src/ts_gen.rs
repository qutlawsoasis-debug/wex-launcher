/// Write all generated TypeScript files to target directory.
pub fn write_bindings_to_dir(target_dir: &Path) -> std::io::Result<()> {
    if !target_dir.exists() {
        fs::create_dir_all(target_dir)?;
    }

    let files = generate_all_bindings();
    for (filename, content) in files {
        let dest = target_dir.join(filename);
        fs::write(dest, content)?;
    }

    Ok(())
}
